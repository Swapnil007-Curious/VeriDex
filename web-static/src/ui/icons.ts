const NS = "http://www.w3.org/2000/svg";
const cache = new Map<string, SVGSVGElement>();

function build(name: string): SVGSVGElement {
  const rows = B[name] ?? B.question ?? [];
  const svg = document.createElementNS(NS, "svg");
  svg.setAttribute("viewBox", "0 0 16 16");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  svg.setAttribute("shape-rendering", "crispEdges");
  svg.setAttribute("class", "px-icon");
  svg.setAttribute("fill", "currentColor");
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let w = 1;
      while (row[x + w] === "#") w++;
      const r = document.createElementNS(NS, "rect");
      r.setAttribute("x", String(x));
      r.setAttribute("y", String(y));
      r.setAttribute("width", String(w));
      r.setAttribute("height", "1");
      svg.appendChild(r);
      x += w;
    }
  });
  return svg;
}

/** A pixel icon (a fresh copy) at ``size`` px (16 or 32 keep the pixels whole). */
export function pixelIcon(name: IconName | string, size = 16): SVGSVGElement {
  let tpl = cache.get(name);
  if (!tpl) {
    tpl = build(name);
    cache.set(name, tpl);
  }
  const svg = tpl.cloneNode(true) as SVGSVGElement;
  svg.setAttribute("width", String(size));
  svg.setAttribute("height", String(size));
  return svg;
}

/** Fill every [data-icon] element under ``root`` that has no icon yet. */
export function hydrateIcons(root: ParentNode = document): void {
  for (const node of root.querySelectorAll<HTMLElement>("[data-icon]")) {
    if (node.querySelector(":scope > svg.px-icon")) continue;
    const name = node.dataset.icon ?? "question";
    node.prepend(pixelIcon(name, Number(node.dataset.iconSize) || 16));
  }
}

/** Swap the icon of an element (e.g. the theme toggle). */
export function setIcon(node: HTMLElement, name: IconName | string): void {
  node.dataset.icon = name;
  node.querySelector(":scope > svg.px-icon")?.remove();
  node.prepend(pixelIcon(name, Number(node.dataset.iconSize) || 16));
}

